const FORMAT_LABEL = {
	article: 'article (通常の記事)',
	visual: 'visual (図解的に整理する記事)',
	dialogue: 'dialogue (健太と美咲の会話)'
}

/** 1 本ぶんの依頼文。日付・テーマ・ネタ・既存タイトルなど、毎回変わる情報はここに入れる */
export function buildUserPrompt({ date, theme, topic, existingTitles, exercises }) {
	const lines = [
		`${date.ymd} 公開の記事を 1 本書いてください。`,
		'',
		`- テーマ: ${theme.label}`,
		`- テーマの方針: ${theme.brief}`,
		`- 形式: ${FORMAT_LABEL[theme.format] ?? theme.format}`,
		`- カテゴリ: ${theme.category}`
	]
	if (topic) {
		lines.push(
			`- ネタ (想定している検索語): ${topic}`,
			'',
			'この検索語で調べる人が何に困っているかを考え、その疑問にまっすぐ答える記事にしてください。'
		)
	} else {
		lines.push(
			'',
			'このテーマのネタ帳が尽きています。下の既存記事と重ならない、検索されそうな具体的な切り口を 1 つ自分で決めて書いてください。決めた切り口は topic に書きます。'
		)
	}
	if ((theme.require_components ?? []).includes('GymCta')) {
		lines.push('', '本文の、ジムを探す・比べる話の流れに合う箇所へ <GymCta> を 1 つ入れてください。')
	}
	if (theme.use_exercises && exercises) {
		lines.push(
			'',
			'アプリに登録されている種目は次のとおりです。記事で扱う種目はこの中から選んでください (読者がアプリでそのまま記録できます)。',
			exercises
		)
	}
	if (existingTitles.length) {
		lines.push('', '既存記事のタイトル (同じタイトル・同じ切り口は避ける):', ...existingTitles.map((t) => `- ${t}`))
	}
	return lines.join('\n')
}

/** 検証に落ちたときの再依頼文 */
export function buildRetryPrompt(errors) {
	return [
		'公開前の自動検証で、次の問題が見つかりました。',
		'',
		...errors.map((error) => `- ${error}`),
		'',
		'該当箇所を直したうえで、すべての項目をもう一度出力してください。問題のなかった部分は変えなくて構いません。禁止表現は、言い換えで同じ主張を残すのではなく、主張そのものを方針に合う形に改めてください。'
	].join('\n')
}
